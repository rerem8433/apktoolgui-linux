TABLES = {"fr": FR}


def set_language(code):
    global _lang
    if not code or code == "Auto":
        loc = os.environ.get("LANGUAGE") or os.environ.get("LC_ALL") or os.environ.get("LC_MESSAGES") \
            or os.environ.get("LANG") or (locale.getlocale()[0] or "")
        code = (loc or "en")[:2].lower()
    _lang = code if code in TABLES else "en"


def tr(s):
    t = TABLES.get(_lang)
    return t.get(s, s) if t else s
